#  შექმენით სია და მომხმარებელს შემოატანინეთ ინდექსი. გამოიყენეთ try და except, რათა პროგრამამ error არ გამოიტანოს თუ ინდექსი სიაში არ არსებობს
my_list  = [10,20,50,70,30]
try:
    index = int(input("შეიყვანეთ ინდექსი: "))
    print("ელემენტი არის:", my_list[index])
except IndexError:
    print('ასეთი ინდექსი არარის სიაში')
except ValueError:
      print(" გთხოვთ შეიყვანოთ მხოლოდ რიცხვი!")
